/**
 * Closed centripetal Catmull–Rom spline through the ring's points, resampled every `step` units.
 * The trace is a Douglas–Peucker polygon (segments ~11 units, corners of 5–12°); at full size
 * every corner read as a facet on the rim. The spline passes through each traced point, so the
 * silhouette stays the reference's, but it turns smoothly between them (centripetal
 * parametrisation: no overshoot or loops where the point spacing is uneven).
 */
function smoothRing(ring: Ring, step: number): Ring {
  const n = ring.length;
  const out: [number, number][] = [];
  const knot = (a: readonly [number, number], b: readonly [number, number]) =>
    Math.max(Math.sqrt(Math.hypot(b[0] - a[0], b[1] - a[1])), 1e-6);
  for (let i = 0; i < n; i++) {
    const p0 = ring[(i - 1 + n) % n];
    const p1 = ring[i];
    const p2 = ring[(i + 1) % n];
    const p3 = ring[(i + 2) % n];
    const t1 = knot(p0, p1);
    const t2 = t1 + knot(p1, p2);
    const t3 = t2 + knot(p2, p3);
    const k = Math.max(1, Math.ceil(Math.hypot(p2[0] - p1[0], p2[1] - p1[1]) / step));
    for (let s = 0; s < k; s++) {
      const t = t1 + ((t2 - t1) * s) / k;
      const pt: [number, number] = [0, 0];
      for (let c = 0; c < 2; c++) {
        // Barry–Goldman pyramid
        const a1 = ((t1 - t) / t1) * p0[c] + (t / t1) * p1[c];
        const a2 = ((t2 - t) / (t2 - t1)) * p1[c] + ((t - t1) / (t2 - t1)) * p2[c];
        const a3 = ((t3 - t) / (t3 - t2)) * p2[c] + ((t - t2) / (t3 - t2)) * p3[c];
        const b1 = ((t2 - t) / t2) * a1 + (t / t2) * a2;
        const b2 = ((t3 - t) / (t3 - t1)) * a2 + ((t - t1) / (t3 - t1)) * a3;
        pt[c] = ((t2 - t) / (t2 - t1)) * b1 + ((t - t1) / (t2 - t1)) * b2;
      }
      out.push(pt);
    }
  }
  return out;
}

